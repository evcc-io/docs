#!/usr/bin/env node
// Usage:
//   node scripts/i18n/terms.mjs <lang>                    writes scripts/i18n/terms/<lang>.md
//   node scripts/i18n/terms.mjs <lang> "English string"   prints matching UI keys with the <lang> value
// Sources: ../evcc/i18n/glossary/{en,<lang>}.json, ../evcc/i18n/{en,<lang>}.json and the en docs.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
  DOCS,
  EVCC,
  LANG_NAMES,
  SCRIPTS,
  evccI18n,
  flatten,
  glossary,
  listPages,
  maskCode,
  splitFrontmatter,
} from "./lib.mjs";

const [lang, query] = process.argv.slice(2);
if (!lang) {
  console.error('usage: terms.mjs <lang> ["English string"]');
  process.exit(2);
}
if (!EVCC) {
  console.error("evcc repo not found (expected ../evcc or EVCC_ROOT)");
  process.exit(2);
}

const enUi = flatten(evccI18n("en"));
const ui = flatten(evccI18n(lang) ?? {});
const byValue = new Map();
for (const [k, v] of Object.entries(enUi)) {
  if (typeof v !== "string") continue;
  const key = v.trim().toLowerCase();
  byValue.set(key, [...(byValue.get(key) ?? []), k]);
}
const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");
const value = (k) => (ui[k] ? ui[k] : "(untranslated in UI)");
// distinct <lang> values for a set of keys: "value (key, key)"
const values = (keys) => {
  const groups = new Map();
  for (const k of keys)
    groups.set(value(k), [...(groups.get(value(k)) ?? []), k]);
  const all = [...groups].map(([v, ks]) => ({ v, keys: ks }));
  const done = all.filter((g) => ui[g.keys[0]]);
  return (done.length ? done : all).slice(0, 3);
};

if (query) {
  const q = query.trim().toLowerCase();
  let keys = byValue.get(q) ?? [];
  if (!keys.length)
    keys = Object.keys(enUi)
      .filter(
        (k) => typeof enUi[k] === "string" && enUi[k].toLowerCase().includes(q),
      )
      .slice(0, 20);
  if (!keys.length)
    console.log(`no UI string matches "${query}", translate naturally`);
  for (const k of keys)
    console.log(`${k}\n  en: ${enUi[k]}\n  ${lang}: ${value(k)}`);
  process.exit(0);
}

// 1. glossary
const gEn = glossary("en");
const gL = glossary(lang) ?? {};
const out = [
  `# ${LANG_NAMES[lang] ?? lang} terms`,
  "",
  `Generated by \`node scripts/i18n/terms.mjs ${lang}\` from the evcc glossary and UI translations. Do not edit by hand.`,
  "",
  "## Glossary",
  "",
  "Agreed term per concept. Base form; inflect as the grammar requires.",
  "",
  `| key | en | description | ${lang} |`,
  "| --- | --- | --- | --- |",
];
for (const [k, e] of Object.entries(gEn))
  out.push(
    `| ${k} | ${cell(e.other)} | ${cell(e.description)} | ${cell(gL[k] ?? "(missing)")} |`,
  );

// 2. UI strings referenced in the en docs
const found = new Map(); // en string -> count
const paths = new Map();
const note = (s) => {
  s = s.trim();
  const k =
    [...found.keys()].find((f) => f.toLowerCase() === s.toLowerCase()) ?? s;
  if (s) found.set(k, (found.get(k) ?? 0) + 1);
};
for (const rel of listPages("en")) {
  const { body } = splitFrontmatter(
    readFileSync(join(DOCS, "en", rel), "utf8"),
  );
  const { masked } = maskCode(body);
  for (const m of masked.matchAll(/\*\*([^*\n]+?)\*\*/g))
    m[1].split("→").forEach(note);
  for (const m of masked.matchAll(
    /<(TabItem|NavCard|Badge)\b[^>]*?\b(label|title|text)="([^"]*)"/g,
  ))
    note(m[3]);
  for (const m of masked.matchAll(
    /\*\*[^*\n]+\*\*(?:\s*→\s*\*\*[^*\n]+\*\*)*/g,
  )) {
    const segs = m[0]
      .replace(/\*\*/g, "")
      .split("→")
      .map((s) => s.trim());
    if (segs.length > 1) paths.set(segs.join(" → "), segs);
  }
}
out.push(
  "",
  "## UI strings used in the docs",
  "",
  "Bold UI names and navigation segments in the English docs that match a UI string exactly (case-insensitive).",
  "Use the exact UI translation inside bold UI references.",
  "",
  `| en | ${lang} | key |`,
  "| --- | --- | --- |",
);
const matched = [...found.keys()]
  .filter((s) => byValue.has(s.toLowerCase()))
  .sort((a, b) => a.localeCompare(b));
for (const s of matched)
  for (const { v, keys } of values(byValue.get(s.toLowerCase()).slice(0, 6)))
    out.push(`| ${cell(s)} | ${cell(v)} | ${keys.slice(0, 3).join(", ")} |`);

// 3. navigation paths
out.push(
  "",
  "## Navigation paths",
  "",
  "Pre-composed `A → B` paths from the English docs. Segments without a UI match are marked with `?` and translated naturally.",
  "",
  `| en | ${lang} |`,
  "| --- | --- |",
);
for (const [p, segs] of [...paths].sort()) {
  const t = segs.map((s) => {
    const keys = byValue.get(s.toLowerCase());
    return keys ? values(keys)[0].v : `${s} ?`;
  });
  out.push(`| ${cell(p)} | ${cell(t.join(" → "))} |`);
}

mkdirSync(join(SCRIPTS, "terms"), { recursive: true });
const file = join(SCRIPTS, "terms", `${lang}.md`);
writeFileSync(file, out.join("\n") + "\n");
console.log(
  `${file}: ${Object.keys(gEn).length} glossary terms, ${matched.length} of ${found.size} UI references matched, ${paths.size} paths`,
);
